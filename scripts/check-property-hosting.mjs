import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const uri = text => `data:text/javascript;base64,${Buffer.from(text).toString('base64')}`;
let source = await fs.readFile('netlify/edge-functions/property-page.js', 'utf8');
source = source.replace('../../src/mock.js', uri(await fs.readFile('src/mock.js','utf8'))).replace('../../src/lib/seo.js', uri(await fs.readFile('src/lib/seo.js','utf8')));
const {default: handler} = await import(uri(source));
const template = await fs.readFile('build/404.html','utf8');
const context = {next: async () => new Response(template, {status:404})};
globalThis.Netlify = {env:{get:()=>null}};
assert.equal((await handler(new Request('https://www.silfira.co.in/properties/atmos-by-solaire'),context)).status,200);
assert.equal((await handler(new Request('https://www.silfira.co.in/properties/not-a-real-property'),context)).status,404);
globalThis.Netlify = {env:{get:key=>key.endsWith('_URL')?'https://example.supabase.co':'test-key'}};
globalThis.fetch = async () => Response.json([{id:'123',slug:'new-listing',title:'New Listing',location_label:'Sargasan',price_min:7500000,price_max:10000000,bedrooms_min:3,bedrooms_max:4,property_assets:[]}]);
const fresh = await handler(new Request('https://www.silfira.co.in/properties/new-listing'),context);
assert.equal(fresh.status,200);
const html = await fresh.text();
assert.ok(html.includes('New Listing, 3–4 BHK'));
assert.equal((html.match(/<title>/g)||[]).length,1);
assert.ok(!html.includes('noindex'));
assert.equal((html.match(/id="site-schema"/g)||[]).length,1);
globalThis.fetch = async () => Response.json([]);
assert.equal((await handler(new Request('https://www.silfira.co.in/properties/not-a-real-property'),context)).status,404);
globalThis.fetch = async () => {throw new Error('offline');};
assert.equal((await handler(new Request('https://www.silfira.co.in/properties/new-listing'),context)).status,503);
console.log('PASS: existing and newly published property HTML/metadata, missing property HTTP 404, and temporary lookup failure HTTP 503.');
